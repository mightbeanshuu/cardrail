-- Per-chunk partial sums written by the first step of the settlement job. Insert-only, so a restarted
-- chunk never double counts: the rows of a rolled-back chunk never existed.
CREATE TABLE settlement_partial (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    settlement_date   DATE         NOT NULL,
    party_type        VARCHAR2(10) NOT NULL,
    party_id          VARCHAR2(16) NOT NULL,
    currency          NUMBER(10)   NOT NULL,
    record_count      NUMBER(10)   NOT NULL,
    gross_minor       NUMBER(19)   NOT NULL,
    interchange_minor NUMBER(19)   NOT NULL,
    net_minor         NUMBER(19)   NOT NULL,
    CONSTRAINT settlement_partial_pk PRIMARY KEY (id),
    CONSTRAINT settlement_partial_party_ck CHECK (party_type IN ('ACQUIRER', 'ISSUER', 'NETWORK'))
);

CREATE INDEX settlement_partial_date_ix ON settlement_partial (settlement_date);

CREATE TABLE settlement_position (
    settlement_date   DATE                     NOT NULL,
    party_type        VARCHAR2(10)             NOT NULL,
    party_id          VARCHAR2(16)             NOT NULL,
    currency          NUMBER(10)               NOT NULL,
    record_count      NUMBER(10)               NOT NULL,
    gross_minor       NUMBER(19)               NOT NULL,
    interchange_minor NUMBER(19)               NOT NULL,
    net_minor         NUMBER(19)               NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT settlement_position_pk PRIMARY KEY (settlement_date, party_type, party_id, currency),
    CONSTRAINT settlement_position_party_ck CHECK (party_type IN ('ACQUIRER', 'ISSUER', 'NETWORK'))
);
