CREATE TABLE interchange_rate (
    category        VARCHAR(16)  NOT NULL,
    rate_bps        INTEGER      NOT NULL,
    fixed_fee_minor BIGINT       NOT NULL,
    description     VARCHAR(100) NOT NULL,
    CONSTRAINT interchange_rate_pk PRIMARY KEY (category),
    CONSTRAINT interchange_rate_bps_ck CHECK (rate_bps BETWEEN 0 AND 10000),
    CONSTRAINT interchange_rate_fixed_ck CHECK (fixed_fee_minor >= 0)
);

CREATE TABLE mcc_interchange_category (
    mcc      VARCHAR(4)  NOT NULL,
    category VARCHAR(16) NOT NULL,
    CONSTRAINT mcc_interchange_category_pk PRIMARY KEY (mcc),
    CONSTRAINT mcc_category_rate_fk FOREIGN KEY (category) REFERENCES interchange_rate (category)
);

CREATE TABLE clearing_record (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    authorization_id      VARCHAR(36)              NOT NULL,
    record_type           VARCHAR(10)              NOT NULL,
    token                 VARCHAR(64)              NOT NULL,
    masked_pan            VARCHAR(19)              NOT NULL,
    issuer_bin            VARCHAR(6)               NOT NULL,
    acquirer_id           VARCHAR(11)              NOT NULL,
    merchant_id           VARCHAR(15)              NOT NULL,
    mcc                   VARCHAR(4)               NOT NULL,
    currency              INTEGER                  NOT NULL,
    amount_minor          BIGINT                   NOT NULL,
    interchange_category  VARCHAR(16)              NOT NULL,
    interchange_fee_minor BIGINT                   NOT NULL,
    business_date         DATE                     NOT NULL,
    occurred_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    status                VARCHAR(20)              NOT NULL,
    settlement_date       DATE,
    settled_at            TIMESTAMP WITH TIME ZONE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT clearing_record_pk PRIMARY KEY (id),
    CONSTRAINT clearing_record_auth_type_uk UNIQUE (authorization_id, record_type),
    CONSTRAINT clearing_record_type_ck CHECK (record_type IN ('CAPTURE', 'REVERSAL')),
    CONSTRAINT clearing_record_status_ck CHECK (status IN ('PENDING_SETTLEMENT', 'SETTLED')),
    CONSTRAINT clearing_record_sign_ck CHECK (
        (record_type = 'CAPTURE' AND amount_minor > 0 AND interchange_fee_minor >= 0)
        OR (record_type = 'REVERSAL' AND amount_minor < 0 AND interchange_fee_minor <= 0)),
    CONSTRAINT clearing_record_settled_ck CHECK (
        status = 'PENDING_SETTLEMENT' OR (settlement_date IS NOT NULL AND settled_at IS NOT NULL))
);

CREATE INDEX clearing_record_pending_ix ON clearing_record (status, business_date);
CREATE INDEX clearing_record_bdate_ix ON clearing_record (business_date, id);
CREATE INDEX clearing_record_sdate_ix ON clearing_record (settlement_date);

CREATE TABLE processed_event (
    authorization_id VARCHAR(36)              NOT NULL,
    event_type       VARCHAR(40)              NOT NULL,
    outcome          VARCHAR(10)              NOT NULL,
    detail           VARCHAR(200),
    source           VARCHAR(200)             NOT NULL,
    processed_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT processed_event_pk PRIMARY KEY (authorization_id, event_type),
    CONSTRAINT processed_event_outcome_ck CHECK (outcome IN ('RECORDED', 'IGNORED'))
);
